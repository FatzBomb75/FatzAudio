#!/usr/bin/env python3
"""Writes src/sjis_table.h: Shift-JIS (Windows code page 932, without the
user-defined area F040-F9FC) to Unicode, from Python's own cp932 codec.

    python3 tools/gen/gen_sjis.py > src/sjis_table.h
"""

TRAILS = list(range(0x40, 0x7F)) + list(range(0x80, 0xFD))
LEADS = [l for l in list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD)) if not 0xF0 <= l <= 0xF9]


def code(lead, trail):
    try:
        c = bytes([lead, trail]).decode("cp932")
    except UnicodeDecodeError:
        return 0
    return ord(c) if len(c) == 1 and ord(c) < 0x10000 else 0


rows = [(l, [code(l, t) for t in TRAILS]) for l in LEADS]
rows = [(l, r) for l, r in rows if any(r)]
print("/* Generated by tools/gen/gen_sjis.py: Shift-JIS (Windows code page 932) double-byte")
print(" * characters to Unicode. sjis_row[lead] is the row in sjis_map (0xFF = not a lead");
print(" * byte); the column is the trail byte's index (0x40-0x7E, then 0x80-0xFC); 0 =")
print(" * unassigned. The user-defined area (leads F0-F9) is left out. */")
print("#ifndef FA_SJIS_TABLE_H")
print("#define FA_SJIS_TABLE_H")
print("#include <stdint.h>")
print()
idx = {l: i for i, (l, _) in enumerate(rows)}
print("static const uint8_t sjis_row[256] = {")
cells = ["0x%02X" % idx.get(b, 0xFF) for b in range(256)]
for i in range(0, 256, 16):
    print("    " + ", ".join(cells[i:i + 16]) + ",")
print("};")
print()
print("static const uint16_t sjis_map[%d][188] = {" % len(rows))
for l, r in rows:
    print("    { /* %02X */" % l)
    for i in range(0, 188, 12):
        print("        " + ", ".join("0x%04X" % c for c in r[i:i + 12]) + ",")
    print("    },")
print("};")
print()
print("#endif")
